function makeLGA(stateCode: string, code: string, name: string): Jurisdiction {
  return {
    code: `${stateCode}-${code}`,
    name,
    level: 'LGA',
    parentCode: stateCode,
    centroidLat: 0,
    centroidLng: 0,
  };
}

