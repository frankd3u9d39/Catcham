export function getDefaultJurisdictions(
  level?: 'FEDERAL' | 'STATE' | 'LGA',
  parentCode?: string
): Jurisdiction[] {
  if (level === 'STATE') {
    return DEFAULT_STATES;
  }
  if (level === 'LGA') {
    if (!parentCode) return [];
    const list = DEFAULT_LGAS_BY_STATE[parentCode.toUpperCase()];
    if (list && list.length > 0) return list;
    return [
      makeLGA(parentCode, 'CENTRAL', `${parentCode} Central / Urban`),
      makeLGA(parentCode, 'GENERAL', `${parentCode} State General Authority`),
    ];
  }
  if (level === 'FEDERAL') {
    return [
      {
        code: 'NG',
        name: 'Federal Republic of Nigeria',
        level: 'FEDERAL',
        parentCode: null,
        centroidLat: 9.08,
        centroidLng: 8.68,
      },
    ];
  }
  return DEFAULT_STATES;
}
